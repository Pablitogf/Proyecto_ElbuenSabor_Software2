"""Puertos (interfaces) que la aplicación necesita del mundo exterior.

Los casos de uso dependen de estas abstracciones, nunca de SQLAlchemy, de la DIAN
o de WebSockets directamente (Principio de Inversión de Dependencias). Cada puerto
tiene un adaptador en `infraestructura/` o `presentacion/`.
"""

from dataclasses import dataclass
from datetime import datetime
from typing import Protocol, Self

from app.dominio.estados_pedido import EstadoPedido
from app.dominio.eventos import EventoDeDominio
from app.dominio.factura import Factura
from app.dominio.inventario import Ingrediente, MovimientoInventario
from app.dominio.jornada import Jornada
from app.dominio.mesa import Mesa
from app.dominio.pago import Pago
from app.dominio.pedido import Pedido
from app.dominio.producto import ProductoMenu
from app.dominio.reserva import Reserva
from app.dominio.usuario import Usuario


# ── Tiempo ─────────────────────────────────────────────────────────────────────
class Reloj(Protocol):
    """Inyectar la hora permite probar reglas de horario sin esperar al reloj real."""

    def ahora(self) -> datetime: ...


# ── Repositorios (patrón Repository) ───────────────────────────────────────────
class RepositorioMesas(Protocol):
    def listar(self) -> list[Mesa]: ...
    def obtener(self, numero: int) -> Mesa | None: ...
    def guardar(self, mesa: Mesa) -> None: ...


class RepositorioProductos(Protocol):
    def listar(self) -> list[ProductoMenu]: ...
    def obtener(self, producto_id: int) -> ProductoMenu | None: ...


class RepositorioIngredientes(Protocol):
    def listar(self) -> list[Ingrediente]: ...
    def obtener(self, ingrediente_id: int) -> Ingrediente | None: ...
    def existe_con_nombre(self, nombre: str) -> bool: ...
    def agregar(self, ingrediente: Ingrediente) -> Ingrediente: ...
    def guardar(self, ingrediente: Ingrediente) -> None: ...


class RepositorioMovimientos(Protocol):
    def agregar(self, movimiento: MovimientoInventario) -> None: ...
    def listar_recientes(self, limite: int) -> list[MovimientoInventario]: ...
    def consumo_desde(self, desde: datetime) -> dict[int, float]: ...
    def salidas_del_pedido(self, pedido_id: int) -> dict[int, float]: ...


class RepositorioPedidos(Protocol):
    def agregar(self, pedido: Pedido) -> Pedido: ...
    def obtener(self, pedido_id: int) -> Pedido | None: ...
    def guardar(self, pedido: Pedido) -> None: ...
    def listar_por_estados(self, estados: frozenset[EstadoPedido]) -> list[Pedido]: ...
    def en_servicio_de_mesa(self, numero_mesa: int) -> Pedido | None: ...
    def contar_por_jornada_y_estados(self, jornada_id: int, estados: frozenset[EstadoPedido]) -> int: ...


class RepositorioPagos(Protocol):
    def agregar(self, pago: Pago) -> Pago: ...
    def listar_por_jornada(self, jornada_id: int) -> list[Pago]: ...
    def de_factura(self, factura_id: int) -> Pago | None: ...


class RepositorioFacturas(Protocol):
    def agregar(self, factura: Factura) -> Factura: ...
    def obtener(self, factura_id: int) -> Factura | None: ...
    def guardar(self, factura: Factura) -> None: ...
    def ultimo_consecutivo(self) -> int: ...
    def listar_por_jornada(self, jornada_id: int) -> list[Factura]: ...
    def listar_recientes(self, limite: int) -> list[Factura]: ...


class RepositorioReservas(Protocol):
    def agregar(self, reserva: Reserva) -> Reserva: ...
    def obtener(self, reserva_id: int) -> Reserva | None: ...
    def guardar(self, reserva: Reserva) -> None: ...
    def listar_pendientes(self) -> list[Reserva]: ...
    def listar_entre(self, desde: datetime, hasta: datetime) -> list[Reserva]: ...


class RepositorioJornadas(Protocol):
    def actual(self) -> Jornada: ...
    def agregar(self, jornada: Jornada) -> Jornada: ...
    def guardar(self, jornada: Jornada) -> None: ...


class RepositorioUsuarios(Protocol):
    def por_nombre_usuario(self, nombre_usuario: str) -> Usuario | None: ...
    def obtener(self, usuario_id: int) -> Usuario | None: ...
    def listar(self) -> list[Usuario]: ...


class UnidadDeTrabajo(Protocol):
    """Patrón Unit of Work: agrupa los repositorios en UNA transacción.
    Si algo falla antes de `confirmar()`, no se guarda nada."""

    mesas: RepositorioMesas
    productos: RepositorioProductos
    ingredientes: RepositorioIngredientes
    movimientos: RepositorioMovimientos
    pedidos: RepositorioPedidos
    pagos: RepositorioPagos
    facturas: RepositorioFacturas
    reservas: RepositorioReservas
    jornadas: RepositorioJornadas
    usuarios: RepositorioUsuarios

    def __enter__(self) -> Self: ...
    def __exit__(self, *args: object) -> None: ...
    def confirmar(self) -> None: ...


class FabricaUnidadDeTrabajo(Protocol):
    def __call__(self) -> UnidadDeTrabajo: ...


# ── Eventos (patrón Observer) ──────────────────────────────────────────────────
class PublicadorEventos(Protocol):
    async def publicar(self, *eventos: EventoDeDominio) -> None: ...


# ── Integraciones externas (patrón Adapter) ────────────────────────────────────
@dataclass(frozen=True)
class RespuestaPasarela:
    aprobada: bool
    codigo_autorizacion: str | None = None
    motivo_rechazo: str | None = None


class PasarelaDePagos(Protocol):
    """IS-01: API REST de la entidad bancaria."""

    def autorizar(self, monto: int, referencia: str) -> RespuestaPasarela: ...


@dataclass(frozen=True)
class RespuestaDIAN:
    aceptada: bool
    codigo: str | None = None
    mensaje: str | None = None
    xml_enviado: str | None = None


class ServicioFacturacionElectronica(Protocol):
    """IS-02: web service SOAP de la DIAN."""

    def enviar_factura(self, factura: Factura, pedido: Pedido) -> RespuestaDIAN: ...
    def enviar_reporte_diario(self, jornada: Jornada, total_ventas: int, facturas: int) -> RespuestaDIAN: ...


# ── Seguridad ──────────────────────────────────────────────────────────────────
class ServicioDeCredenciales(Protocol):
    def verificar_pin(self, pin: str, hash_pin: str) -> bool: ...
    def emitir_token(self, usuario: Usuario) -> str: ...
    def leer_token(self, token: str) -> int | None: ...
